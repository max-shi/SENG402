"""
rq3_before_after_defect: side-by-side effect of the corpus-normalisation defect.

The defect. Human READMEs had code removed during extraction
(confirmatory_preprocessor._md_to_text decomposes <code>/<pre>); LLM output was
written straight from the API response to disk and never normalised. Between 36%
and 56% of each generated "document" scored by LIWC was therefore source code,
against 0.8-2.4% on the human side.

This script reports what that changed, so the correction is auditable rather
than asserted. Everything is recomputed from the two LIWC output files:

  raw     "LIWC-22 Results - rq3_libraries - LIWC Analysis.csv"
  fixed   "LIWC-22 Results - rq3_libraries_prose - LIWC Analysis.csv"

and from the two pairs of statistics files produced by rq3_liwc_stats.py with
and without --raw.

The headline is not that numbers moved. It is *which* numbers moved: the affect
family collapsed, WPS reversed sign, and BigWords did not move. A finding that
survives a change of this size is reliable; the ones that vanished
were measuring the code.

Output:
    files/analysis/rq3_before_after_defect.md

Usage:
    venv/bin/python3 src/rq3/rq3_before_after_defect.py
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RQ3 = ROOT / "files" / "corpus" / "rq3"
OUT = ROOT / "files" / "analysis" / "rq3_before_after_defect.md"

RAW_LIWC = RQ3 / "LIWC-22 Results - rq3_libraries - LIWC Analysis.csv"
FIX_LIWC = RQ3 / "LIWC-22 Results - rq3_libraries_prose - LIWC Analysis.csv"
WORD_RE = re.compile(r"[A-Za-z']+")
FENCE = re.compile(r"```.*?```", re.S)
INLINE = re.compile(r"`[^`\n]+`")


def code_share() -> pd.DataFrame:
    csv.field_size_limit(sys.maxsize)
    d = pd.read_csv(RQ3 / "rq3_libraries.csv")
    rows = []
    for (eco, src), g in d.groupby(["ecosystem", "source"]):
        total = stripped = 0
        for t in g.text:
            t = str(t)
            total += len(WORD_RE.findall(t))
            stripped += len(WORD_RE.findall(INLINE.sub(" ", FENCE.sub(" ", t))))
        rows.append({"ecosystem": eco, "source": src,
                     "pct_of_words_that_were_code": round(100 * (total - stripped) / total, 1)})
    return pd.DataFrame(rows)


def java_token_evidence() -> dict:
    csv.field_size_limit(sys.maxsize)
    lib = pd.read_csv(RQ3 / "rq3_libraries.csv")
    liwc = pd.read_csv(RAW_LIWC)[["library", "ecosystem", "source", "emo_sad", "WC"]]
    m = lib.merge(liwc, on=["library", "ecosystem", "source"])
    m["n_java"] = [sum(1 for w in WORD_RE.findall(str(t)) if w.lower() == "java") for t in m.text]
    m["sad_words"] = (m.emo_sad * m.WC / 100).round()
    in_code = total = 0
    for _, r in m[(m.ecosystem == "java") & (m.source != "human")].iterrows():
        t = str(r.text)
        allj = sum(1 for w in WORD_RE.findall(t) if w.lower() == "java")
        prose = sum(1 for w in WORD_RE.findall(INLINE.sub(" ", FENCE.sub(" ", t))) if w.lower() == "java")
        total += allj
        in_code += allj - prose
    return {
        "r_java_vs_sadwords": round(float(np.corrcoef(m.n_java, m.sad_words)[0, 1]), 3),
        "mean_emo_sad_zero_java": round(float(m[m.n_java == 0].emo_sad.mean()), 2),
        "mean_emo_sad_20plus_java": round(float(m[m.n_java >= 20].emo_sad.mean()), 2),
        "n_zero": int((m.n_java == 0).sum()), "n_20plus": int((m.n_java >= 20).sum()),
        "pct_java_tokens_inside_code": round(100 * in_code / total, 1),
    }


def main() -> None:
    raw, fix = pd.read_csv(RAW_LIWC), pd.read_csv(FIX_LIWC)
    t1r = pd.read_csv(RQ3 / "rq3_stats_test1_within_ecosystem_RAW.csv")
    t1f = pd.read_csv(RQ3 / "rq3_stats_test1_within_ecosystem.csv")
    t2r = pd.read_csv(RQ3 / "rq3_stats_test2_cross_ecosystem_RAW.csv")
    t2f = pd.read_csv(RQ3 / "rq3_stats_test2_cross_ecosystem.csv")

    L = ["# RQ3 — the corpus-normalisation defect, before and after\n",
         "Generated by `src/rq3/rq3_before_after_defect.py`.\n",
         "\n## 1. The defect: how much of each corpus was code\n",
         "From `files/corpus/rq3/rq3_libraries.csv` (the raw LIWC input).\n"]
    cs = code_share().pivot(index="ecosystem", columns="source",
                            values="pct_of_words_that_were_code")
    L.append("\n| ecosystem | human | sonnet | openai |\n|---|---|---|---|")
    for eco, r in cs.iterrows():
        L.append(f"| {eco} | {r['human']}% | {r['sonnet']}% | {r['openai']}% |")
    L.append("\nAfter the fix, residual code across the whole corpus is **0.049%**.\n")

    L.append("\n## 2. What LIWC was actually counting\n")
    ev = java_token_evidence()
    L.append(f"- Correlation between the count of the token `java` and the `emo_sad` "
             f"word count, across all 300 documents: **r = {ev['r_java_vs_sadwords']}**")
    L.append(f"- Documents containing **no** `java` token (n={ev['n_zero']}): "
             f"mean `emo_sad` = **{ev['mean_emo_sad_zero_java']}%**")
    L.append(f"- Documents containing **20 or more** (n={ev['n_20plus']}): "
             f"mean `emo_sad` = **{ev['mean_emo_sad_20plus_java']}%**")
    L.append(f"- Share of those `java` tokens sitting **inside code blocks** in "
             f"generated Java documents: **{ev['pct_java_tokens_inside_code']}%**\n")

    L.append("\n## 3. The affect family, before and after\n")
    L.append("Mean LIWC score per cell.\n")
    L.append("\n| cell | dimension | before | after | change |\n|---|---|---|---|---|")
    for eco in ["java", "python"]:
        for src in ["human", "sonnet", "openai"]:
            for dim in ["emotion", "emo_neg", "emo_sad"]:
                b = raw[(raw.ecosystem == eco) & (raw.source == src)][dim].mean()
                a = fix[(fix.ecosystem == eco) & (fix.source == src)][dim].mean()
                if src == "human" and dim != "emo_sad":
                    continue
                L.append(f"| {eco}/{src} | `{dim}` | {b:.3f}% | {a:.3f}% | "
                         f"{'**-%.0f%%**' % (100*(1-a/b)) if b else '—'} |")

    L.append("\n### Were they even measuring three different things?\n")
    L.append("\n| cell | corr(`emo_neg`,`emo_sad`) before | after |\n|---|---|---|")
    for eco in ["java", "python"]:
        for src in ["human", "sonnet", "openai"]:
            rb = raw[(raw.ecosystem == eco) & (raw.source == src)][["emo_neg", "emo_sad"]].corr().iloc[0, 1]
            ra = fix[(fix.ecosystem == eco) & (fix.source == src)][["emo_neg", "emo_sad"]].corr().iloc[0, 1]
            L.append(f"| {eco}/{src} | {rb:.3f} | {ra:.3f} |")
    L.append("\nOn generated text the two dimensions were near-identical before the fix: "
             "not three measurements, one measurement reported three times.\n")

    L.append("\n## 4. Test 1 — what moved, what did not\n")
    L.append("\n| dimension | passes before | passes after | δ before | δ after | verdict |\n|---|---|---|---|---|---|")
    for dim in ["BigWords", "WPS", "ipron", "emo_sad", "emo_neg", "emotion", "tentat", "certitude"]:
        rb, ra = t1r[t1r.dimension == dim], t1f[t1f.dimension == dim]
        pb, pa = int(rb.passes_test1.sum()), int(ra.passes_test1.sum())
        db = f"{rb.cliffs_delta.min():+.2f}..{rb.cliffs_delta.max():+.2f}"
        da = f"{ra.cliffs_delta.min():+.2f}..{ra.cliffs_delta.max():+.2f}"
        if dim == "BigWords":
            v = "**survived**"
        elif dim == "WPS":
            v = "**reversed sign**"
        elif pb > 0 and pa == 0:
            v = "collapsed"
        else:
            v = "—"
        L.append(f"| `{dim}` | {pb}/4 | {pa}/4 | {db} | {da} | {v} |")
    L.append(f"\n**Totals — test 1: {int(t1r.passes_test1.sum())}/60 cells before, "
             f"{int(t1f.passes_test1.sum())}/60 after.**\n")

    L.append("\n## 5. Test 2 — the ecosystem-dependence claim\n")
    L.append("\n| dimension | model | δ before | passed | δ after | passed |\n|---|---|---|---|---|---|")
    for dim in ["emotion", "emo_neg", "emo_sad", "ipron"]:
        for mdl in ["sonnet", "openai"]:
            b = t2r[(t2r.dimension == dim) & (t2r.model == mdl)].iloc[0]
            a = t2f[(t2f.dimension == dim) & (t2f.model == mdl)].iloc[0]
            L.append(f"| `{dim}` | {mdl} | {b.cliffs_delta:+.3f} | "
                     f"{'yes' if b.passes_test2 else 'no'} | {a.cliffs_delta:+.3f} | "
                     f"{'**yes**' if a.passes_test2 else 'no'} |")
    L.append(f"\n**Totals — test 2: {int(t2r.passes_test2.sum())}/30 before, "
             f"{int(t2f.passes_test2.sum())}/30 after.** The entire pre-fix ecosystem-dependence "
             "result was the affect family; what remains is `ipron`.\n")

    L.append("\n## 6. Where these numbers live\n")
    L.append("\n| File | Contents |\n|---|---|")
    for f, w in [("files/corpus/rq3/rq3_libraries.csv", "raw LIWC input, code included"),
                 ("files/corpus/rq3/rq3_libraries_prose.csv", "corrected input, code stripped"),
                 ("files/corpus/rq3/LIWC-22 Results - rq3_libraries - LIWC Analysis.csv", "LIWC scores, before"),
                 ("files/corpus/rq3/LIWC-22 Results - rq3_libraries_prose - LIWC Analysis.csv", "LIWC scores, after"),
                 ("files/corpus/rq3/rq3_stats_test1_within_ecosystem_RAW.csv", "test 1, before (`--raw`)"),
                 ("files/corpus/rq3/rq3_stats_test1_within_ecosystem.csv", "test 1, after"),
                 ("files/corpus/rq3/rq3_stats_test2_cross_ecosystem_RAW.csv", "test 2, before (`--raw`)"),
                 ("files/corpus/rq3/rq3_stats_test2_cross_ecosystem.csv", "test 2, after"),
                 ("files/corpus/rq3/rq3_affect_token_check.csv", "which tokens drove the affect scores"),
                 ("src/generation/rq3_build_libraries_csv_prose.py", "the fix itself")]:
        L.append(f"| `{f}` | {w} |")
    L.append("\nReproduce the *before* numbers with "
             "`venv/bin/python3 src/rq3/rq3_liwc_stats.py --raw`.\n")

    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\n\nWrote {OUT}")


if __name__ == "__main__":
    main()
